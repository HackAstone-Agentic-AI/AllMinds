// Builds one printable PDF with everything a teacher needs for a lesson:
// the plan, visual supports (with images) and a letter for families.

export interface PackSection {
  title: string;
  text: string;
  images?: { label: string; url: string }[];
}

export async function buildClassPackPdf(packTitle: string, sections: PackSection[]): Promise<Blob> {
  const { default: jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const margin = 18;
  const width = doc.internal.pageSize.getWidth() - margin * 2;
  const bottom = doc.internal.pageSize.getHeight() - margin;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text(doc.splitTextToSize(packTitle, width), margin, 40);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(90, 90, 90);
  doc.text(`Class pack generated by All Minds | ${new Date().toLocaleDateString('en-ZA')}`, margin, 60);
  sections.forEach((section, index) => doc.text(`${index + 1}. ${section.title}`, margin, 75 + index * 7));
  doc.setFontSize(9);
  doc.text('AI-generated material. Review before use with learners and families.', margin, bottom);

  for (const section of sections) {
    doc.addPage();
    let y = margin;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(11, 79, 92);
    doc.text(section.title.toUpperCase(), margin, y);
    y += 9;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(40, 40, 40);
    for (const line of doc.splitTextToSize(section.text || '(not available)', width)) {
      if (y > bottom) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += 5.5;
    }
    for (const image of section.images ?? []) {
      doc.addPage();
      doc.setFont('helvetica', 'bold');
      doc.text(image.label, margin, margin);
      try {
        doc.addImage(image.url, image.url.startsWith('data:image/png') ? 'PNG' : 'JPEG', margin, margin + 6, width, width * 0.7);
      } catch {
        doc.setFont('helvetica', 'normal');
        doc.text('[Image could not be embedded]', margin, margin + 12);
      }
    }
  }
  return doc.output('blob');
}
